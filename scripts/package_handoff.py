#!/usr/bin/env python3
"""Package the Turnkeep offline release candidate as one zip (T048).

  .venv/bin/python scripts/package_handoff.py --output release/TURNKEEP_RC.zip

What it does, in order:
  1. Refuses unless the rebuilt release artifacts match the current tree
     (release/artifacts/manifest.json commit == current HEAD, D-R5-2):
     the shipped manifest must describe the shipped source snapshot.
     1b. Refuses unless the wheel/sdist in the artifacts match the
     current src/ byte-for-byte (P0-R3-03 guard — same check as
     scripts/verify_release.py, mirrored here so a stale wheel can
     never be zipped in the first place).
     1c. Re-evaluates tree cleanliness at packaging time instead of
     trusting the manifest's stale ``tracked_tree_clean`` snapshot:
     refuses if any shipped src/ file is modified, staged, or untracked
     relative to the artifact manifest's ``built_at``, or if any shipped
     src/ file's mtime is newer than ``built_at``.
  2. Collects source, locks, build scripts, examples, tests, schemas,
     docs, fixtures, adapters, benchmarks (protocol/scenarios only),
     the UI source, the release artifacts, the final handoff and a
     desensitised evidence summary into a deterministic zip
     (sorted entries, fixed timestamps from the HEAD commit time,
     fixed uid/gid/mode). The handoff docs' HEAD lines are stamped at
     packaging time (P2-R4-08): the repo copies carry the token
     HEAD@PACKAGING, which is replaced with the packaging HEAD here,
     so the SHIPPED docs name the exact manifest head instead of
     going stale every round.
  3. Writes release/DELIVERY_MANIFEST.json (version 0.1.0, commit,
     grading, file list + sha256, known gaps, next actions). The copy
     of DELIVERY_MANIFEST.json inside the zip is identical to the
     on-disk copy except for ``archive_sha256``, which is null in-zip
     (a file cannot hash itself) and filled in on disk after the zip
     is written; the difference is stated in both copies.
  4. Never uploads, messages, logs in or spends anything. No public
     release happens here: this is a local candidate + draft only.

Excluded, always: .venv, .git, __pycache__, *.pyc, node_modules,
ui/dist, .pytest_cache, .tmp, test-results, playwright-report,
*.db / *.sqlite*, src/turnkeep.egg-info, state/ and evidence/ raw
files (they contain machine paths under this machine's home directory), and
benchmarks/results/ (run outputs). A desensitised evidence summary
(evidence-summary.json, built in memory from evidence/GATE_MATRIX.json
+ the frozen perf record, with no absolute paths) is included instead.
Any collected text file that still contains this machine's home path
or a private-key marker is excluded and recorded, never shipped silently.

Exit codes: 0 packaged, 1 failure (e.g. artifact manifest commit
mismatch), 2 refused.
"""
import argparse
import hashlib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = "0.1.0"
CONTRACT_VERSION = "0.1"
PREFIX = f"turnkeep-{VERSION}"
ZIP_FIXED_DT = (1980, 1, 1, 0, 0, 0)

# Top-level files shipped at the zip root.
TOP_FILES = [
    "pyproject.toml", "LICENSE", "NOTICE", "SECURITY.md",
    "README.md", "README.zh-CN.md", "HANDOFF.md", "conftest.py",
]
# Directories shipped recursively (with the exclusions below).
INCLUDE_DIRS = [
    "src", "tests", "scripts", "specs", "docs", "examples", "fixtures",
    "adapters", "benchmarks", "requirements", "ops", "ui", ".github",
    "release",
]
EXCLUDE_DIR_PARTS = {
    ".venv", ".git", "__pycache__", "node_modules", ".pytest_cache",
    ".tmp", "test-results", "playwright-report", "ui/dist",
    "src/turnkeep.egg-info", "benchmarks/results",
}
EXCLUDE_TOP_DIRS = {"state", "evidence"}
EXCLUDE_SUFFIXES = {".db", ".sqlite", ".sqlite3", ".db-wal", ".db-shm",
                    ".pyc"}
EXCLUDE_FILES = {
    # Empty R0 placeholder, never a lock (see SBOM notes / manifest).
    "requirements/ui.lock",
    # Build cache, not source.
    "ui/tsconfig.tsbuildinfo",
    # Generated by this script itself; always written fresh, never
    # collected from a previous run (otherwise the file list would
    # carry a duplicate self-entry and re-runs would not be stable).
    "release/DELIVERY_MANIFEST.json",
}
# Files under release/ that are NOT shipped: the zip itself, and the
# release-candidate build's own output dir is shipped only via artifacts.
EXCLUDE_RELEASE = {"release/TURNKEEP_RC.zip"}
def _forbidden_markers():
    """Markers that must never appear in a shipped text file.

    The machine home path is derived at runtime (Path.home()), never
    written as a literal: a literal in this file would make the scan
    drop this file itself. The key marker is a real PEM block (armour
    header + base64 body), not the bare words: leak-detector scripts
    legitimately contain the words as patterns.
    """
    home = str(Path.home())
    pem = re.compile(
        r"-----BEGIN [A-Z ]*PRIVATE KEY-----\s*\n[0-9A-Za-z+/=\r\n]{40,}")
    return home, pem


def _sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def _git(*args):
    r = subprocess.run(["git", *args], cwd=str(ROOT), capture_output=True,
                       text=True, encoding="utf-8")
    return r.stdout.strip() if r.returncode == 0 else None


def _is_excluded(rel):
    posix = rel.as_posix()
    if posix in EXCLUDE_FILES or posix in EXCLUDE_RELEASE:
        return True
    parts = rel.parts
    if parts[0] in EXCLUDE_TOP_DIRS:
        return True
    if any(part in EXCLUDE_DIR_PARTS for part in parts):
        return True
    # Directory-prefix exclusions (e.g. benchmarks/results, ui/dist).
    for prefix in ("benchmarks/results", "ui/dist",
                   "src/turnkeep.egg-info"):
        if posix == prefix or posix.startswith(prefix + "/"):
            return True
    if rel.suffix in EXCLUDE_SUFFIXES:
        return True
    return False


def _collect():
    """Return (files, excluded) where files maps rel path -> bytes."""
    files = {}
    excluded = []
    for name in TOP_FILES:
        p = ROOT / name
        if p.is_file():
            files[Path(name)] = p.read_bytes()
        else:
            excluded.append(f"missing top-level file (not shipped): {name}")
    for dirname in INCLUDE_DIRS:
        base = ROOT / dirname
        if not base.is_dir():
            excluded.append(f"missing dir (not shipped): {dirname}")
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(ROOT)
            if _is_excluded(rel):
                excluded.append(f"excluded: {rel.as_posix()}")
                continue
            files[rel] = p.read_bytes()
    # tasks/backlog.json is a symlink to state/backlog.json; ship the
    # resolved content as a regular file (state/ itself is excluded).
    backlog = ROOT / "tasks" / "backlog.json"
    if backlog.is_file():
        files[Path("tasks/backlog.json")] = backlog.read_bytes()
    return files, excluded


def _files_from_dir(src_root):
    """{rel-posix -> bytes} for every file under src_root (recursive),
    .py and non-.py alike (P2-R4-07: migrations/*.sql included).

    Mirror of the same helper in scripts/verify_release.py — the two
    scripts are standalone (no shared import), so keep them in sync.
    """
    out = {}
    for p in sorted(Path(src_root).rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts:
            continue
        out[p.relative_to(src_root).as_posix()] = p.read_bytes()
    return out


def _files_from_wheel(wheel_path):
    """{rel-posix under turnkeep/ -> bytes} for every file in the wheel."""
    out = {}
    with zipfile.ZipFile(wheel_path) as zf:
        for name in zf.namelist():
            if not name.startswith("turnkeep/"):
                continue
            out[name[len("turnkeep/"):]] = zf.read(name)
    return out


def _files_from_sdist(sdist_path):
    """{rel-posix under src/turnkeep/ -> bytes} for every packaged file."""
    out = {}
    with tarfile.open(sdist_path, "r:gz") as tf:
        for m in tf.getmembers():
            if not m.isfile():
                continue
            parts = m.name.split("/")
            # sdist layout: <name>-<version>/src/turnkeep/<rel>
            if len(parts) >= 4 and parts[1] == "src" and parts[2] == "turnkeep":
                f = tf.extractfile(m)
                if f is not None:
                    out["/".join(parts[3:])] = f.read()
    return out


def _diff_trees(artifact_files, src_files, label):
    """Compare one packaged file tree against src/. Returns a list of
    problem strings (empty when identical)."""
    problems = []
    for rel in sorted(set(artifact_files) | set(src_files)):
        if rel not in src_files:
            problems.append(f"{label}: extra file not in src/: {rel}")
        elif rel not in artifact_files:
            problems.append(f"{label}: missing file present in src/: {rel}")
        elif artifact_files[rel] != src_files[rel]:
            problems.append(f"{label}: differs from src/: {rel}")
    return problems


# Token in the repo copies of the handoff docs (HANDOFF.md,
# release/FINAL_HANDOFF.md) marking where the packaging HEAD goes.
# A hand-maintained doc cannot name its own commit's hash — the hash
# does not exist until the commit is made — so the docs went stale
# every round (P2-R4-08: FINAL_HANDOFF said 57285cfc while the
# manifest said 422984d). Packaging replaces the token with the real
# head, so the SHIPPED docs always name the manifest head exactly.
HEAD_STAMP_TOKEN = "HEAD@PACKAGING"


def _stamp_packaging_head(files, head):
    """Replace HEAD_STAMP_TOKEN with the packaging HEAD in the two
    handoff docs (in place). Returns the list of stamped rel paths.
    Only these two files are stamped: the token string also appears in
    scripts/package_handoff.py itself (this constant) and in the guard
    tests, which must NOT be rewritten. Raises ValueError if the token
    survives in either handoff doc afterwards — a shipped doc must name
    the packaging HEAD, not the token. Must run BEFORE the delivery
    manifest is computed, so the manifest hashes the stamped bytes."""
    stamped = []
    token = HEAD_STAMP_TOKEN.encode("utf-8")
    for rel in (Path("HANDOFF.md"), Path("release/FINAL_HANDOFF.md")):
        data = files.get(rel)
        if data is None:
            continue
        if token in data:
            files[rel] = data.replace(token, head.encode("utf-8"))
            stamped.append(rel.as_posix())
    for rel in (Path("HANDOFF.md"), Path("release/FINAL_HANDOFF.md")):
        data = files.get(rel)
        if data is not None and token in data:
            raise ValueError(
                f"HEAD@PACKAGING token survives stamping in "
                f"{rel.as_posix()}; the shipped docs must name the "
                f"packaging HEAD, not the token")
    return stamped


def _check_artifacts_match_src(artifacts_dir, src_root, manifest):
    """P0-R3-03 guard: the wheel/sdist must be built from the current
    src/. Returns a list of problem strings (empty when they match)."""
    src_files = _files_from_dir(src_root)
    if not src_files:
        return ["wheel-vs-source check: no files found under src/"]
    files = [f["path"] for f in manifest.get("files") or []]
    wheels = [f for f in files if f.endswith(".whl")]
    sdists = [f for f in files if f.endswith(".tar.gz")
              and "ui-dist" not in f and "source" not in f]
    if not wheels and not sdists:
        return ["wheel-vs-source check: no wheel or sdist listed in the "
                "artifact manifest"]
    problems = []
    for wheel in wheels:
        p = Path(artifacts_dir) / wheel
        if not p.is_file():
            problems.append(f"wheel-vs-source check: wheel missing: {wheel}")
            continue
        problems.extend(_diff_trees(_files_from_wheel(p), src_files,
                                     f"wheel {wheel}"))
    for sdist in sdists:
        p = Path(artifacts_dir) / sdist
        if not p.is_file():
            problems.append(f"wheel-vs-source check: sdist missing: {sdist}")
            continue
        problems.extend(_diff_trees(_files_from_sdist(p), src_files,
                                     f"sdist {sdist}"))
    return problems


def _parse_built_at(value):
    """Parse the artifact manifest's built_at ISO timestamp, or None."""
    if not value:
        return None
    try:
        dt = datetime.fromisoformat(str(value))
    except ValueError:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


def _tree_clean_problems(built_at, root):
    """Re-evaluate tree cleanliness at packaging time (P0-R3-03).

    The artifact manifest's ``tracked_tree_clean`` is a snapshot from
    build time and goes stale the moment the tree changes afterwards,
    so it is never trusted here. Two independent signals are used, and
    either one refuses packaging:

    1. ``git status --porcelain``: any tracked src/ file that is
       modified or staged, or any untracked file under src/, means the
       shipped src/ no longer matches what the wheel was built from.
    2. File mtimes vs ``built_at``: any shipped src/ file whose mtime
       is newer than the manifest's build timestamp was touched after
       the build, even if git cannot see it (e.g. a file that is
       tracked but whose change was staged and then the index
       rewritten, or a clock/git edge case). The mtime check is the
       backstop; the git check is the primary signal.

    Returns a list of problem strings (empty when clean). ``root`` is
    the repo root; ``built_at`` is an aware datetime or None (None
    means the manifest carries no usable build timestamp, which is
    itself a refusal).
    """
    if built_at is None:
        return ["tree-cleanliness check: artifact manifest has no usable "
                "built_at timestamp; cannot prove the artifacts match the "
                "current tree"]
    problems = []
    r = subprocess.run(["git", "status", "--porcelain"], cwd=str(root),
                       capture_output=True, text=True, encoding="utf-8")
    if r.returncode != 0:
        return ["tree-cleanliness check: git status failed; cannot prove "
                "the tree is clean"]
    for line in r.stdout.splitlines():
        status, _, path = line[:2], line[2:3], line[3:]
        path = path.strip().strip('"')
        if path.startswith("src/"):
            kind = ("untracked" if status.strip() == "??"
                    else "modified/staged")
            problems.append(
                f"tree-cleanliness check: src/ file {kind} since build: "
                f"{path} (git status {status.strip() or status!r})")
    built_ts = built_at.timestamp()
    src_root = Path(root) / "src"
    for p in sorted(src_root.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(root)
        if _is_excluded(rel):
            continue
        if p.stat().st_mtime > built_ts:
            problems.append(
                f"tree-cleanliness check: shipped src/ file modified after "
                f"the artifact build ({built_at.isoformat()}): "
                f"{rel.as_posix()}")
    return problems


def _scan_forbidden(files):
    """Drop any collected text file carrying a machine path or a real
    private-key block. Returns (kept, dropped)."""
    home, pem = _forbidden_markers()
    kept, dropped = {}, []
    for rel, data in files.items():
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            kept[rel] = data  # binary (wheel/sdist/tarball): not scanned
            continue
        if home in text or pem.search(text):
            # Do not quote the marker in the log: the log itself is
            # shipped inside the zip (DELIVERY_MANIFEST.json).
            dropped.append(f"dropped (machine-path/secret marker): "
                           f"{rel.as_posix()}")
            continue
        kept[rel] = data
    return kept, dropped


def _evidence_summary(head):
    """Desensitised evidence summary (in-memory only; never written to
    the tree as a file, so no raw evidence path leaks into the zip)."""
    matrix_path = ROOT / "evidence" / "GATE_MATRIX.json"
    matrix = json.loads(matrix_path.read_text(encoding="utf-8"))
    gates = []
    for g in matrix.get("gates", []):
        ev = [e for e in g.get("evidence", [])
              if "/home/" not in e]
        gates.append({"id": g.get("id"), "status": g.get("status"),
                      "claim": g.get("claim"),
                      "tasks": g.get("tasks", []),
                      "notes": g.get("notes", ""),
                      "evidence": ev})
    perf_path = ROOT / "evidence" / "platforms" / "perf.json"
    perf = json.loads(perf_path.read_text(encoding="utf-8"))
    perf = {k: v for k, v in perf.items()
            if k not in ("hostname", "path", "cwd", "machine")}
    return {
        "product": "Turnkeep (working name)",
        "version": VERSION,
        "contract_version": CONTRACT_VERSION,
        "head_sha": head,
        "generated_by": "T048 (scripts/package_handoff.py)",
        "note": ("Desensitised summary only. Raw evidence files under "
                 "evidence/ and state/ are NOT shipped: they contain "
                 "machine paths. Full evidence lives in the source "
                 "checkout (evidence/FINAL_REVIEW.md, "
                 "evidence/GATE_MATRIX.json, evidence/tasks/)."),
        "grading": matrix.get("grading", {}),
        "gates": gates,
        "performance_frozen_record": perf,
        "full_review": "evidence/FINAL_REVIEW.md (not shipped; see grading above)",
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default="release/TURNKEEP_RC.zip")
    args = ap.parse_args()
    out = (ROOT / args.output).resolve()

    head = _git("rev-parse", "HEAD")
    commit_ts = _git("log", "-1", "--format=%ct")
    if not head:
        print("FAIL: not a git checkout; cannot record commit.",
              file=sys.stderr)
        return 1
    epoch = int(commit_ts) if commit_ts else 0
    built_at = (datetime.fromtimestamp(epoch, tz=timezone.utc).isoformat()
                if epoch else None)

    # Guard (D-R5-2): the shipped artifact manifest must match HEAD.
    art_manifest_path = ROOT / "release" / "artifacts" / "manifest.json"
    if not art_manifest_path.is_file():
        print("FAIL: release/artifacts/manifest.json missing; rebuild "
              "artifacts first (.venv/bin/python scripts/build_release.py "
              "--clean --output release/artifacts).", file=sys.stderr)
        return 1
    art_manifest = json.loads(art_manifest_path.read_text(encoding="utf-8"))
    if art_manifest.get("commit") != head:
        print(f"FAIL: artifact manifest commit "
              f"{art_manifest.get('commit')} != HEAD {head}; rebuild "
              f"artifacts at packaging time before zipping.",
              file=sys.stderr)
        return 1

    # Guard (P0-R3-03, 1c): re-evaluate tree cleanliness at packaging
    # time. The manifest's tracked_tree_clean is a snapshot from build
    # time; the R3 ZIP shipped a stale wheel precisely because packaging
    # trusted it after the tree had changed. Refuse if any shipped
    # src/ file moved after the artifact build.
    clean_problems = _tree_clean_problems(
        _parse_built_at(art_manifest.get("built_at")),
        ROOT)
    if clean_problems:
        for prob in clean_problems:
            print(f"FAIL: {prob}", file=sys.stderr)
        print("FAIL: tree changed after the artifact build; commit the "
              "rework and rebuild the artifacts before packaging.",
              file=sys.stderr)
        return 1

    # Guard (P0-R3-03, 1b): the wheel/sdist must match the current
    # src/ byte-for-byte. Refuse to ship a stale wheel.
    artifacts_dir = ROOT / "release" / "artifacts"
    mismatch = _check_artifacts_match_src(artifacts_dir,
                                          ROOT / "src" / "turnkeep",
                                          art_manifest)
    if mismatch:
        for prob in mismatch:
            print(f"FAIL: wheel-vs-source mismatch: {prob}", file=sys.stderr)
        print("FAIL: shipped wheel/sdist does not match the current src/; "
              "rebuild the artifacts before packaging.", file=sys.stderr)
        return 1

    final_handoff = ROOT / "release" / "FINAL_HANDOFF.md"
    if not final_handoff.is_file():
        print("FAIL: release/FINAL_HANDOFF.md missing; write it before "
              "packaging.", file=sys.stderr)
        return 1

    files, excluded = _collect()
    files, dropped = _scan_forbidden(files)
    excluded.extend(dropped)

    # P2-R4-08: stamp the packaging HEAD into the handoff docs before
    # the manifest is computed, so the shipped docs name the exact
    # manifest head (and the manifest hashes the stamped bytes).
    _stamp_packaging_head(files, head)

    # Evidence summary (in-memory, desensitised).
    summary = _evidence_summary(head)
    summary_bytes = (json.dumps(summary, indent=2, ensure_ascii=False)
                     + "\n").encode("utf-8")
    files[Path("evidence-summary.json")] = summary_bytes

    # DELIVERY_MANIFEST.json: file list covers every zip entry EXCEPT
    # itself (a file cannot hash itself); archive_sha256 is null in-zip
    # and filled in on disk after the zip is written.
    grading = summary["grading"]
    zip_entries = sorted(files.keys(), key=lambda p: p.as_posix())
    file_list = [{"path": f"{PREFIX}/{rel.as_posix()}",
                  "sha256": _sha256_bytes(files[rel]),
                  "bytes": len(files[rel])} for rel in zip_entries]
    manifest = {
        "product": "Turnkeep (working name)",
        "version": VERSION,
        "contract_version": CONTRACT_VERSION,
        "head_sha": head,
        "packaging_commit": head,
        "packaging_note": ("Packaging does not commit git, so the HEAD "
                           "recorded here is the HEAD the zip was built "
                           "from; the artifact manifest commit matches "
                           "it (D-R5-2)."),
        "built_at": built_at,
        "source_date_epoch": epoch,
        "archive_name": out.name,
        "archive_sha256": None,
        "archive_sha256_note": ("Null in the copy shipped inside the zip: "
                                "a file cannot hash the archive that "
                                "contains it. The on-disk copy at "
                                "release/DELIVERY_MANIFEST.json carries "
                                "the real sha256 of the finished zip; "
                                "verify_handoff.py checks it."),
        "release_artifacts": {
            "manifest_commit": art_manifest.get("commit"),
            "manifest_matches_head": True,
            "reproducible": art_manifest.get("reproducibility", {}).get(
                "identical"),
            "files": len(art_manifest.get("files", [])),
        },
        "grading": grading,
        "known_gaps": art_manifest.get("known_gaps", {}),
        "files": file_list,
        "file_count": len(file_list),
        "total_bytes": sum(len(files[rel]) for rel in zip_entries),
        "excluded": excluded,
        "excluded_note": ("Excluded, always: .venv, .git, __pycache__, "
                          "*.pyc, node_modules, ui/dist, .pytest_cache, "
                          ".tmp, test-results, *.db/*.sqlite*, "
                          "src/turnkeep.egg-info, state/ and evidence/ "
                          "raw files (machine paths), "
                          "benchmarks/results/, "
                          "requirements/ui.lock (empty placeholder, not "
                          "a lock). A desensitised evidence-summary.json "
                          "is shipped instead of raw evidence."),
        "next_actions": [
            "Drive + GitHub upload of this RC authorised by Sam 2026-11-10 "
            "~09:08 GMT (private repo; no public release). T043 set aside "
            "for now; Sam tests Windows/macOS himself after the Drive "
            "upload.",
            "T026 follow-up (optional, disclosed): re-run the Codex forward "
            "leg (S1/S2/S3b/S4) once the M365 backend is healthy; record "
            "tool-call logs + client versions in evidence/live-clients/.",
            "T042: complete as run (two clean live runs, finding MIXED); "
            "no further runs unless Sam asks.",
            "T043: real Windows/macOS install + doctor + J01/J05 runs; "
            "perf fix (read-set snapshots + indexed recall) then "
            "re-measure against the same thresholds (finish p95 500 ms, "
            "recall p95 1000 ms).",
            "Trademark clearance + dependency vulnerability scan "
            "(pip-audit / npm audit) before any public release.",
            "Durable packaging fixes (not blocking OFFLINE_RC): demo.py "
            "fixtures via importlib.resources; regenerate or "
            "remove requirements/ui.lock. (The pyproject.toml "
            "package-data fix is done since the R4 rework, P2-R4-09.)",
        ],
        "publication": {
            "authorised": True,
            "attempted": True,
            "reason": ("Drive + GitHub upload of this release candidate "
                       "authorised by Sam 2026-11-10 ~09:08 GMT (private "
                       "repo turnkeep; no public release). Uploads run as "
                       "a separate step after packaging; status and links "
                       "are recorded in state/CONTROL_STATE.json (not "
                       "shipped in this zip)."),
        },
    }
    manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False)
                      + "\n").encode("utf-8")
    files[Path("release/DELIVERY_MANIFEST.json")] = manifest_bytes
    file_list.append({
        "path": f"{PREFIX}/release/DELIVERY_MANIFEST.json",
        "sha256": None,
        "bytes": len(manifest_bytes),
        "note": ("Present in the zip; excluded from its own hash list "
                 "(sha256 null). The on-disk copy at "
                 "release/DELIVERY_MANIFEST.json is identical except "
                 "archive_sha256, which is filled in there; "
                 "verify_handoff.py checks both."),
    })
    # Rebuild the manifest bytes with the final file list (self-entry
    # included, hash null) so the shipped copy is complete. The
    # self-entry byte count and total depend on the serialised length,
    # so iterate to a fixed point (digit counts are stable after one
    # pass; two passes are run and the result asserted stable).
    manifest["file_count"] = len(file_list)
    for _ in range(3):
        manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False)
                          + "\n").encode("utf-8")
        files[Path("release/DELIVERY_MANIFEST.json")] = manifest_bytes
        for entry in file_list:
            if entry["path"].endswith("release/DELIVERY_MANIFEST.json"):
                entry["bytes"] = len(manifest_bytes)
        manifest["total_bytes"] = (sum(len(files[rel])
                                       for rel in zip_entries)
                                   + len(manifest_bytes))
    final_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False)
                   + "\n").encode("utf-8")
    assert final_bytes == manifest_bytes, (
        "DELIVERY_MANIFEST self-reference did not converge")

    # Deterministic zip: sorted entries, fixed timestamp, fixed attrs.
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED,
                         compresslevel=9) as zf:
        for rel in sorted(files.keys(), key=lambda p: p.as_posix()):
            arcname = f"{PREFIX}/{rel.as_posix()}"
            info = zipfile.ZipInfo(arcname, date_time=ZIP_FIXED_DT)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            info.create_system = 3
            zf.writestr(info, files[rel])
    zip_bytes = buf.getvalue()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(zip_bytes)

    # On-disk manifest: same content, archive_sha256 filled in.
    manifest["archive_sha256"] = _sha256_bytes(zip_bytes)
    manifest["archive_sha256_note"] = (
        "sha256 of the finished release/TURNKEEP_RC.zip.")
    disk_manifest = ROOT / "release" / "DELIVERY_MANIFEST.json"
    disk_manifest.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")

    print(json.dumps({
        "status": "PACKAGED",
        "output": str(out),
        "head_sha": head,
        "files": len(file_list),
        "total_bytes": manifest["total_bytes"],
        "archive_sha256": manifest["archive_sha256"],
        "archive_bytes": len(zip_bytes),
        "excluded_count": len(excluded),
        "grading": {k: v.get("verdict") for k, v in grading.items()},
    }, indent=2, ensure_ascii=False))
    return 0


